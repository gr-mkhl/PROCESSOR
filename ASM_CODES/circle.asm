$CENTER_X 400
$CENTER_Y 300
$WIDTH 800
$HEIGHT 600
$RED -16776961
; RED = FF 00 00 FF in (int)



IN
POP DX
CALL : FILL_MEM
DRAW
HLT

: FILL_MEM
    PUSH 0
    POP AX
    PUSH 0
    POP BX
    CALL : BEG_Y_CYCLE
    RET

: BEG_Y_CYCLE
    PUSH AX
    PUSH $HEIGHT
    JB : Y_CYCLE
    RET

: Y_CYCLE
    CALL : BEG_X_CYCLE
    PUSH 0
    POP BX
    PUSH 1
    PUSH AX
    ADD
    POP AX
    JMP : BEG_Y_CYCLE

: BEG_X_CYCLE
    PUSH BX
    PUSH $WIDTH
    JB : X_CYCLE
    RET

: X_CYCLE
    CALL : IF_CIRCLE
    PUSH BX
    PUSH 1
    ADD
    POP BX
    JMP : BEG_X_CYCLE


: IF_CIRCLE
    PUSH BX
    PUSH $CENTER_X
    SUB
    PUSH BX
    PUSH $CENTER_X
    SUB
    MUL
    PUSH AX
    PUSH $CENTER_Y
    SUB
    PUSH AX
    PUSH $CENTER_Y
    SUB
    MUL
    ADD
    PUSH DX
    PUSH DX
    MUL
    JBE : YES
    RET

: YES
    PUSH AX
    PUSH $WIDTH
    MUL
    PUSH BX
    ADD
    POP CX
    PUSH $RED
    POP [CX]
    RET



